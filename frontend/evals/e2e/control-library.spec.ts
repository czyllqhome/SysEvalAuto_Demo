import { test, expect } from '@playwright/test'

test.use({ actionTimeout: 15000 })

test('maintain controls, round-trip Excel and confirm a tag-driven classification', async ({ page }) => {
  test.skip(process.env.SYSEVAL_LIBRARY_E2E !== 'true', 'Run explicitly against an isolated QA database.')
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  const registration = await page.request.post('/api/v1/auth/register', { data: {
    email: `library-${crypto.randomUUID()}@example.test`, password: 'Synthetic-Library-Test-Only',
    name: 'Library test owner', organization: 'Isolated library QA',
  } })
  expect(registration.ok()).toBeTruthy()
  const session = await registration.json()
  await page.addInitScript(() => localStorage.setItem('scope-language', 'en'))
  await page.goto('/library')
  await page.getByRole('button', { name: 'New control', exact: true }).click()
  await page.getByLabel('Control code', { exact: true }).fill('QA-REMOTE-1')
  await page.getByLabel('Assessment object', { exact: true }).fill('Test application')
  await page.getByRole('listbox', { name: 'Assessment profiles (multiple)', exact: true }).selectOption('MLPS2_REFERENCE')
  await page.getByRole('combobox', { name: 'Domain', exact: true }).selectOption('BOUNDARY')
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill('Protect remote administration')
  await page.getByRole('textbox', { name: 'Requirement', exact: true }).fill('Protect authentication information on remote administration channels.')
  await page.getByRole('textbox', { name: 'Verification and evidence', exact: true }).fill('Inspect transport protection and an example access record.')
  await page.getByRole('combobox', { name: 'Applicability', exact: true }).selectOption('conditional')
  await page.getByLabel('Fact tag', { exact: true }).selectOption('ops.remote_admin')
  await page.getByLabel('Requirement, applicability and source reviewed').check()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByText('Draft saved. Publish to use it for new assessments.')).toBeVisible()
  await page.getByRole('button', { name: 'Review publication', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm publication', exact: true }).click()
  await expect(page.getByText('Library published.', { exact: true })).toBeVisible()
  const exported = await page.request.get('/api/v1/library/export')
  await page.locator('input[type=file]').setInputFiles({ name: 'controls.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: await exported.body() })
  await expect(page.getByRole('heading', { name: 'Upload preview' })).toBeVisible()
  await expect(page.getByText('QA-REMOTE-1 · unchanged', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Apply to draft', exact: true }).click()
  await expect(page.getByText('Applied to draft. Review each mapping before publication.')).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('control-library.png'), fullPage: true })

  const created = await page.request.post('/api/v1/systems', { headers: { 'X-CSRF-Token': session.csrf }, data: { name: 'Remote access QA' } })
  expect(created.ok()).toBeTruthy()
  const detail = await created.json()
  await page.goto(`/systems/${detail.system.id}/classification`)
  await page.getByLabel('MLPS', { exact: true }).uncheck()
  await page.getByLabel('CUSTOM', { exact: true }).check()
  await page.getByRole('button', { name: 'Expand additional questions' }).click()
  await page.getByLabel(/Is remote administration used/).selectOption('yes')
  await page.getByRole('button', { name: 'Preview grading and controls', exact: true }).click()
  await expect(page.getByText('Applicable: 1 · Unknown: 0', { exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('tag-classification.png'), fullPage: true })
  await page.getByRole('button', { name: 'Confirm initial grading', exact: true }).click()
  await expect(page).toHaveURL(/\/brief$/)
  const confirmed = await (await page.request.get(`/api/v1/systems/${detail.system.id}`)).json()
  expect(confirmed.system.classification.facts['ops.remote_admin']).toBe('yes')
  expect(confirmed.system.classification.scheme).toBe('SYS-SCREEN/2')
  expect(failures).toEqual([])
})
