import { expect, test } from '@playwright/test'

test('current grading matrix and reorganized navigation fit Chinese desktop and English mobile without writes', async ({ page }, testInfo) => {
  const unexpected: string[] = []
  await page.route('**/api/v1/**', route => {
    const request = route.request(), path = new URL(request.url()).pathname
    if (request.method() === 'GET' && path === '/api/v1/auth/session') return route.fulfill({ json: { user: { id: 'admin', name: 'Administration', role: 'owner', is_admin: true, org_id: 'demo' }, csrf: 'offline', model_configured: false } })
    unexpected.push(`${request.method()} ${path}`)
    return route.fulfill({ status: 403, json: { code: 'FORBIDDEN' } })
  })
  await page.setViewportSize({ width: 1505, height: 1105 })
  await page.goto('/method')
  await expect(page.getByRole('heading', { name: '系统等级如何确定？' })).toBeVisible()
  const method = page.locator('.grading-method')
  await expect(method.locator('.method-card')).toHaveCount(3)
  const rights = method.getByRole('table').first().locator('tbody tr').first()
  await expect(rights.locator('td').nth(2)).toHaveText('3级')
  await expect(rights.locator('td').nth(2)).toHaveClass('matrix-grade grade-3')
  await expect(method).not.toContainText('E09')
  await expect(method).not.toContainText('E10')
  await expect(method).not.toContainText('示例：')
  await expect(method).not.toContainText('零损害与未知答案如何处理')
  await expect(method).not.toContainText('从矩阵结果到初步建议')
  const populationRow = method.getByRole('row', { name: 'D01：个人信息 100,000 人及以上 3 级' })
  await expect(populationRow.getByRole('cell')).toHaveText('3 级')
  await expect(method.getByRole('row', { name: 'D01：个人信息 0–9,999 人 1 级' }).getByRole('cell')).toHaveText('1 级')
  await expect(method.getByRole('row', { name: 'D01：个人信息 10,000–99,999 人 2 级' }).getByRole('cell')).toHaveText('2 级')
  const nav = page.getByRole('navigation', { name: '主导航' })
  await expect(nav.locator('section[aria-label="规则"]').getByRole('link', { name: 'RBAC 职责矩阵' })).toBeVisible()
  await expect(nav.locator('section[aria-label="审计"]').getByRole('link', { name: '审计日志' })).toBeVisible()
  await expect(nav.locator('section[aria-label="配置"]').getByRole('link', { name: '审计日志' })).toHaveCount(0)
  await expect(page.getByText('ASSESSMENT & SUPPLIER COLLABORATION', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('grading-method-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '切换为 English' }).click()
  await expect(page.getByRole('heading', { name: 'How is the system grade determined?' })).toBeVisible()
  await expect(rights.locator('td').nth(2)).toHaveText('3Level')
  await expect(method.getByRole('row', { name: 'D01: personal information for 100,000 people or more 3 Level' }).getByRole('cell')).toHaveText('3 Level')
  const englishNav = page.getByRole('navigation', { name: 'Main navigation' })
  await expect(englishNav.locator('section[aria-label="Rules"]').getByRole('link', { name: 'RBAC matrix' })).toHaveAttribute('href', '/rbac')
  await expect(englishNav.locator('section[aria-label="Audit"]').getByRole('link', { name: 'Audit logs' })).toHaveAttribute('href', '/audit')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('grading-method-mobile.png'), fullPage: true })
  expect(unexpected).toEqual([])
})
