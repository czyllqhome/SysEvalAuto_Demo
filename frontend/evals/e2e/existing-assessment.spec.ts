import { test, expect } from '@playwright/test'
import { prepareScope } from './assessment-fixture'

test.use({ actionTimeout: 15000 })

test('create existing assessment, verify evidence and close only after retest', async ({ page }) => {
  const failures: string[] = []
  page.on('pageerror', e => failures.push(e.message))
  const registered = await page.request.post('/api/v1/auth/register', { data: { email: `existing-${crypto.randomUUID()}@example.test`,
    password: 'Synthetic-existing-test-only', name: 'Assessment QA owner', organization: 'Isolated current-state QA' } })
  expect(registered.ok()).toBeTruthy()
  await page.addInitScript(() => localStorage.setItem('scope-language', 'en'))
  await page.goto('/team')
  const projectForm = page.getByRole('form', { name: 'Create project', exact: true })
  await projectForm.getByRole('button', { name: 'Create an existing-system assessment project' }).click()
  await projectForm.getByLabel('Project name').fill('Operations QA')
  await projectForm.getByRole('button', { name: 'Create project', exact: true }).click()
  await expect(page.getByText(/Project created\./)).toBeVisible()
  await page.goto('/')
  await page.getByRole('button', { name: 'Existing-system assessment', exact: true }).click()
  const creation = page.getByRole('dialog')
  await creation.getByLabel('Assessment name').fill('Running portal QA')
  await creation.getByRole('combobox', { name: 'Project', exact: true }).selectOption({ label: 'Operations QA · Existing-system assessment' })
  await creation.getByLabel('System asset name').fill('Portal asset')
  await creation.getByLabel('Assessment scope').fill('Live production portal')
  const today = new Date().toISOString().slice(0, 10), later = new Date(Date.now() + 86400_000 * 30).toISOString().slice(0, 10)
  await creation.getByLabel('Assessment reference date').fill(today)
  await creation.getByLabel('Environment', { exact: true }).fill('production')
  await creation.getByLabel('System version', { exact: true }).fill('v1')
  await creation.getByRole('button', { name: 'Create assessment', exact: true }).click()
  await expect(page).toHaveURL(/\/systems\/.+\/discovery$/)
  const sid = new URL(page.url()).pathname.split('/')[2]
  await prepareScope(page, sid)
  await page.goto(`/systems/${sid}/controls`)
  await page.getByRole('button', { name: 'Confirm scope & start verification' }).click()
  await expect(page).toHaveURL(/\/existing$/)
  await page.getByRole('button', { name: 'Register evidence', exact: true }).click()
  let modal = page.getByRole('dialog')
  await modal.getByLabel('Evidence content or controlled-source description').fill('QA audit record')
  await modal.getByLabel('Collection date').fill(today)
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(modal).not.toBeVisible()
  await page.getByRole('button', { name: 'Verify', exact: true }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Implementation conclusion').selectOption('partial')
  await modal.getByLabel('Rationale', { exact: true }).fill('Some denied operations are missing')
  await modal.getByLabel('Verification method').fill('Inspect audit log')
  await modal.getByRole('checkbox', { name: /QA audit record/ }).check()
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(modal).not.toBeVisible()
  await page.getByRole('button', { name: 'Review and publish report' }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Report summary and risk review').fill('Audit coverage needs remediation')
  if (await modal.getByLabel('Classification exception approval rationale').count()) await modal.getByLabel('Classification exception approval rationale').fill('Reviewed QA classification')
  await modal.getByRole('combobox', { name: 'Impact', exact: true }).selectOption('high')
  await modal.getByRole('combobox', { name: 'Likelihood', exact: true }).selectOption('medium')
  await modal.getByLabel('Risk rationale').fill('Investigation requires complete records')
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(modal).not.toBeVisible()
  await expect(page.getByRole('link', { name: 'Download Markdown report' })).toBeVisible()
  await page.getByRole('button', { name: 'Create plan', exact: true }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Accountable owner').selectOption({ label: 'Assessment QA owner' })
  await modal.getByLabel('Due date').fill(later)
  await modal.getByLabel('Remediation scope').fill('Enable complete audit logging')
  await modal.getByLabel('Acceptance criteria (one per line)').fill('All denied actions are logged')
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(modal).not.toBeVisible()
  await page.getByRole('button', { name: 'Confirm current plan hash' }).click()
  await page.getByRole('button', { name: 'Register evidence', exact: true }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Evidence content or controlled-source description').fill('QA delivery evidence')
  await modal.getByLabel('Collection date').fill(today)
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(modal).not.toBeVisible()
  await page.getByRole('button', { name: 'Submit completion', exact: true }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Actual completion and delivery description').fill('Audit configuration enabled')
  await modal.getByRole('checkbox', { name: /QA delivery evidence/ }).check()
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(modal).not.toBeVisible()
  await page.getByRole('button', { name: 'Retest', exact: true }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Retest result').selectOption('yes')
  await modal.getByLabel('Retest rationale and acceptance results').fill('Denied actions now appear')
  await modal.getByRole('checkbox', { name: /QA delivery evidence/ }).check()
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(modal).not.toBeVisible()
  await page.getByRole('button', { name: 'Complete disposition', exact: true }).click()
  modal = page.getByRole('dialog')
  await modal.getByLabel('Next assessment date').fill(later)
  await modal.getByRole('button', { name: 'Confirm and save' }).click()
  await expect(page.getByText('Assessment complete', { exact: true })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('existing-assessment-complete.png'), fullPage: true })
  expect(failures).toEqual([])
})
