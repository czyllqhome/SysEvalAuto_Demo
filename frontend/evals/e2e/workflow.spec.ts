import { test, expect } from '@playwright/test'
import { prepareScope } from './assessment-fixture'

test.use({ actionTimeout: 15000 })

test('customer and supplier independently agree on a traceable baseline', async ({ browser, baseURL }) => {
  const ownerContext = await browser.newContext({ baseURL })
  const supplierContext = await browser.newContext({ baseURL })
  await ownerContext.addInitScript(() => localStorage.setItem('scope-language', 'en'))
  await supplierContext.addInitScript(() => localStorage.setItem('scope-language', 'en'))
  const page = await ownerContext.newPage()
  const supplier = await supplierContext.newPage()
  const suffix = crypto.randomUUID().slice(0, 8)
  const password = `Local-Test-${crypto.randomUUID()}`
  try {
    await page.goto('/')
    await page.getByRole('button', { name: 'New here? Create a workspace' }).click()
    await page.getByLabel('Your name').fill('Customer test owner')
    await page.getByLabel('Organization', { exact: true }).fill('Browser test organization')
    await page.getByLabel('Email', { exact: true }).fill(`browser-owner-${suffix}@example.test`)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Create account', exact: true }).click()
    await page.getByRole('button', { name: 'New-system assessment', exact: true }).first().click()
    await page.getByRole('dialog').getByLabel('Assessment name').fill('Customer service portal')
    await page.getByRole('dialog').getByRole('button', { name: 'Create assessment', exact: true }).click()
    await expect(page).toHaveURL(/\/systems\/.+\/discovery$/)
    const sid = new URL(page.url()).pathname.split('/')[2]
    await prepareScope(page, sid)
    await page.goto(`/systems/${sid}/controls`)
    await page.getByRole('button', { name: 'Confirm scope & generate PRD' }).click()
    await page.getByLabel('I reviewed scope, sources, and acceptance criteria').check()
    await page.getByRole('button', { name: 'Approve PRD', exact: true }).click()
    await page.getByRole('button', { name: 'Send to supplier' }).click()
    const systemPath = new URL(page.url()).pathname.split('/').slice(0, 3).join('/')
    await page.getByLabel('Supplier organization', { exact: true }).fill('Browser test supplier')
    await page.getByLabel('Supplier approver email').fill(`browser-supplier-${suffix}@example.test`)
    await page.getByRole('button', { name: 'Publish task & create invitation' }).click()
    const invitation = await page.getByLabel('Invitation link — copy and share').inputValue()
    await supplier.goto(invitation)
    await supplier.getByLabel('Your name').fill('Supplier test approver')
    await supplier.getByLabel('Password', { exact: true }).fill(password)
    await supplier.getByRole('button', { name: 'Create account', exact: true }).click()
    await supplier.getByRole('link', { name: /01 Customer service portal/ }).click()
    await supplier.getByRole('button', { name: 'Fill blank responses' }).click()
    await supplier.getByRole('dialog').getByLabel('Implementation plan', { exact: true }).fill('Implement each requirement and jointly verify retained acceptance evidence.')
    await supplier.getByRole('button', { name: 'Apply to blank responses' }).click()
    await supplier.getByRole('button', { name: 'Submit responses' }).click()
    await page.goto(`${systemPath}/impact`)
    await page.getByLabel('Bulk review rationale').fill('Customer test owner accepts the commitment and schedules evidence verification before release.')
    await page.getByRole('button', { name: 'Accept unresolved findings with rationale' }).click()
    await page.getByLabel('Exception review rationale').fill('No classification exceptions or control exclusions; customer owner is accountable for acceptance checks.')
    await page.getByRole('button', { name: 'Save review decisions' }).click()
    await page.getByRole('button', { name: 'Freeze baseline for joint confirmation' }).click()
    await page.getByLabel('I accept this scope, commitments, and recorded exceptions on behalf of my party').check()
    await page.getByRole('button', { name: 'Confirm this baseline' }).click()
    await expect(page.getByRole('button', { name: 'Save & mark ready for development' })).toBeDisabled()
    await supplier.goto(`${systemPath}/agreement`)
    await supplier.getByLabel('I accept this scope, commitments, and recorded exceptions on behalf of my party').check()
    await supplier.getByRole('button', { name: 'Confirm this baseline' }).click()
    await page.getByRole('button', { name: 'Save & mark ready for development' }).click()
    await expect(page.getByText('Saved as ready for development', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Start delivery evidence tracking' }).click()
    await expect(page).toHaveURL(/\/delivery\//)
    const deliveryPath = new URL(page.url()).pathname
    await supplier.goto(deliveryPath)
    const cards = supplier.locator('article.paper-panel')
    const count = await cards.count()
    expect(count).toBeGreaterThan(0)
    for (let index = 0; index < count; index++) {
      const card = cards.nth(index)
      await card.getByLabel('Completion and evidence description').fill('Verified allowed and denied operations on v2')
      await card.getByLabel('Environment', { exact: true }).fill('production')
      await card.getByLabel('System version', { exact: true }).fill('v2')
      await card.getByLabel('Collection date', { exact: true }).fill(new Date().toISOString().slice(0, 10))
      await card.getByLabel('Upload screenshot or file (20 MiB maximum each)').setInputFiles({ name: 'acceptance.txt', mimeType: 'text/plain', buffer: Buffer.from('Denied operation was rejected and logged.') })
      await expect(card.getByRole('link', { name: 'acceptance.txt' }).first()).toBeVisible()
      for (const checkbox of await card.getByRole('checkbox').all()) await checkbox.check()
      await card.getByRole('button', { name: 'Save draft', exact: true }).click()
      await card.getByRole('button', { name: 'Submit evidence', exact: true }).click()
      await expect(card.getByText('Awaiting review', { exact: true }).first()).toBeVisible()
    }
    await page.reload()
    const firstReview = page.locator('article.paper-panel').first()
    await firstReview.getByLabel('Review rationale').fill('Please provide additional context')
    await firstReview.getByRole('button', { name: 'Save review decision' }).click()
    await expect(firstReview.getByText('Changes or evidence required', { exact: true })).toBeVisible()
    await supplier.reload()
    await cards.first().getByRole('button', { name: 'Submit evidence', exact: true }).click()
    await expect(cards.first().getByText('Awaiting review', { exact: true }).first()).toBeVisible()
    await page.reload()
    await expect(page.getByRole('combobox', { name: 'Decision', exact: true })).toHaveCount(count)
    for (let index = 0; index < count; index++) {
      const card = page.locator('article.paper-panel').nth(index)
      await card.getByRole('combobox', { name: 'Decision', exact: true }).selectOption('PASS')
      for (const checkbox of await card.getByRole('checkbox').all()) await checkbox.check()
      await card.getByLabel('Review rationale').fill('Actual target version verified')
      await card.getByRole('button', { name: 'Save review decision' }).click()
      await expect(card.getByText('Passed', { exact: true })).toBeVisible()
    }
    await page.getByRole('button', { name: 'Complete delivery review', exact: true }).click()
    await expect(page.getByText(/Delivery review complete/)).toBeVisible()
    await page.screenshot({ path: test.info().outputPath('delivery-review-complete.png'), fullPage: true })
  } finally {
    await ownerContext.close()
    await supplierContext.close()
  }
})
