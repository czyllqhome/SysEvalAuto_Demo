import { test, expect } from '@playwright/test'

test('MLPS intake saves, reloads, uploads evidence and explains independent impacts', async ({ page }) => {
  test.skip(process.env.SYSEVAL_MLPS_E2E !== 'true', 'Requires an explicitly isolated QA database.')
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  const registered = await page.request.post('/api/v1/auth/register', { data: { email: `mlps-${crypto.randomUUID()}@example.test`, password: 'Synthetic-MLPS-Test-Only', name: 'QA owner', organization: 'Isolated MLPS QA' } })
  expect(registered.ok()).toBeTruthy()
  const session = await registered.json()
  const headers = { 'X-CSRF-Token': session.csrf }
  const created = await page.request.post('/api/v1/systems', { headers, data: { name: '采购协同系统 · MLPS 问卷验证' } })
  expect(created.ok()).toBeTruthy()
  const detail = await created.json(), sid = detail.system.id
  await page.goto(`/systems/${sid}/classification`)
  await expect(page.getByRole('heading', { name: '从系统事实，到有依据的初步定级' })).toBeVisible()
  await page.getByLabel('运营/使用该系统的单位名称？').fill('测试运营单位')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByText('草稿已载入 / 已保存')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('运营/使用该系统的单位名称？')).toHaveValue('测试运营单位')
  await page.screenshot({ path: test.info().outputPath('mlps-overview.png'), fullPage: false })
  await page.getByRole('button', { name: /F.*核心影响判断/ }).click()
  const info = page.getByRole('article').filter({ hasText: '业务信息被泄露、篡改或丢失后，会影响谁？' })
  await info.getByLabel('受侵害客体 1', { exact: true }).selectOption('rights')
  await info.getByLabel('损害程度 1', { exact: true }).selectOption('2')
  await info.getByLabel('F07 个人和企业的合法权益 判断理由').fill('采购记录篡改会造成严重合同损失，依据 BIA-1。')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByText('草稿已载入 / 已保存')).toBeVisible()
  await page.getByRole('button', { name: /B.*系统部署与连接/ }).click()
  await page.getByLabel('B07 上传材料').setInputFiles({ name: 'topology.txt', mimeType: 'text/plain', buffer: Buffer.from('Synthetic topology evidence') })
  await expect(page.getByText(/下载已上传材料/)).toBeVisible()
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  await expect(page.getByText('草稿已载入 / 已保存')).toBeVisible()
  await page.getByRole('button', { name: '检查与初步结果', exact: true }).click()
  await page.getByRole('button', { name: '检查问卷并计算初步等级' }).click()
  await expect(page.getByText('仅为已知影响的等级下限，仍有未知影响。')).toBeVisible()
  await expect(page.getByRole('button', { name: '确认初步建议，继续录入系统信息' })).toBeDisabled()
  await page.screenshot({ path: test.info().outputPath('mlps-review.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: /B.*系统部署与连接/ }).click()
  await page.screenshot({ path: test.info().outputPath('mlps-mobile.png'), fullPage: false })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
